export type Locale = "en" | "zh";

type I18nContextValue = {
  locale: Locale;
  apiLocale: "en" | "zh-CN";
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, values?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("en");

  useEffect(() => {
    const stored = window.localStorage.getItem("quantai-locale");
    const initial = stored === "zh" || stored === "en"
      ? stored
      : window.navigator.language.toLowerCase().startsWith("zh") ? "zh" : "en";
    const frame = window.requestAnimationFrame(() => setLocaleState(initial));
    return () => window.cancelAnimationFrame(frame);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale === "zh" ? "zh-CN" : "en";
  }, [locale]);

  const setLocale = useCallback((nextLocale: Locale) => {
    setLocaleState(nextLocale);
    window.localStorage.setItem("quantai-locale", nextLocale);
  }, []);

  const t = useCallback((key: TranslationKey, values?: Record<string, string | number>) => {
    const template = locale === "zh" ? chinese[key] : english[key];
    return Object.entries(values ?? {}).reduce(
      (result, [name, value]) => result.replaceAll(`{${name}}`, String(value)),
      template,
    );
  }, [locale]);

  const value = useMemo<I18nContextValue>(() => ({
    locale,
    apiLocale: locale === "zh" ? "zh-CN" : "en",
    setLocale,
    t,
  }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used within I18nProvider.");
  return context;
}
